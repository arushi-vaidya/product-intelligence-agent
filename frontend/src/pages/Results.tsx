function MetricCard({
  label,
  value,
  description,
}: {
  label: string;
  value: string | number;
  description: string;
}) {

  return (

    <div className="metric-card">

      <span>
        {label}
      </span>

      <strong>
        {value}
      </strong>

      <small>
        {description}
      </small>

    </div>
  );
}


function TabIntro({
  title,
  description,
}: {
  title: string;
  description: string;
}) {

  return (

    <div className="tab-intro">

      <h2>
        {title}
      </h2>

      <p>
        {description}
      </p>

    </div>
  );
}


function EmptyState({
  text,
}: {
  text: string;
}) {

  return (
    <div className="empty-state">
      {text}
    </div>
  );
}