/* ============================================================
   HELPERS
   ============================================================ */

function toDisplayText(
  value: unknown
): string {
  if (
    value === null ||
    value === undefined
  ) {
    return "—";
  }

  if (typeof value === "string") {
    return value;
  }

  if (
    typeof value === "number" ||
    typeof value === "boolean"
  ) {
    return String(value);
  }

  if (Array.isArray(value)) {
    return value
      .map((item) =>
        toDisplayText(item)
      )
      .join(", ");
  }

  if (
    typeof value === "object"
  ) {
    return Object.entries(
      value as Record<string, unknown>
    )
      .map(
        ([key, item]) =>
          `${formatFieldName(key)}: ${toDisplayText(item)}`
      )
      .join(" · ");
  }

  return String(value);
}


function formatFieldName(
  value: string
): string {
  return value
    .replace(/_/g, " ")
    .replace(/\b\w/g, (char) =>
      char.toUpperCase()
    );
}


function formatConfidence(
  value?: number | null
): string {
  if (
    value === undefined ||
    value === null
  ) {
    return "—";
  }

  return `${Math.round(
    value * 100
  )}%`;
}


function getSpecValue(
  spec?: Specification
): string {
  if (!spec) {
    return "—";
  }

  const value =
    spec.value !== undefined &&
    spec.value !== null
      ? String(spec.value)
      : "";

  const unit =
    spec.unit
      ? ` ${spec.unit}`
      : "";

  return `${value}${unit}`.trim() || "—";
}


/*
 * Enrichment generated by Gemini may contain:
 *
 * string
 * array
 * object
 * null
 *
 * We normalize everything before rendering.
 * This prevents React errors caused by trying to
 * render objects directly as JSX children.
 */

function normalizeList(
  value: unknown
): string[] {
  if (!value) {
    return [];
  }

  if (Array.isArray(value)) {
    return value.map(
      (item) =>
        toDisplayText(item)
    );
  }

  return [
    toDisplayText(value),
  ];
}


